const GLYPHS: Record<string, readonly number[]> = {}
for (const [ch, src] of Object.entries(SRC)) {
  const rows = src.split("/")
  GLYPHS[ch] = rows.map(r => parseInt(r.replace(/#/g, "1").replace(/\./g, "0"), 2))
}

export function glyph(ch: string): readonly number[] | null {
  return Object.prototype.hasOwnProperty.call(GLYPHS, ch) ? GLYPHS[ch]! : null
}

export function textWidth(s: string, scale = 1): number {
  const n = [...s].length
  return n === 0 ? 0 : (n * GLYPH_ADVANCE - 1) * scale
}
